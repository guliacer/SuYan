function interpolate(text: string, values?: TranslationValues): string {
  if (!values) return text;
  return text.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}

export function translateUiText(language: AppLanguage, text: string, values?: TranslationValues): string {
  const translated = language === "en-US"
    ? featureGuideTranslations[text]
      ?? recommendationTranslations[text]
      ?? additionalTranslations[text]
      ?? translations[text]
      ?? translateUiStatusText(text)
      ?? text
    : text;
  return interpolate(translated, values);
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const language = useLibraryStore((state) => state.language);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<LocaleContextValue>(() => ({
    language,
    isEnglish: language === "en-US",
    t: (text, values) => translateUiText(language, text, values),
  }), [language]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale(): LocaleContextValue {
  const value = useContext(LocaleContext);
  if (!value) {
    throw new Error("useLocale must be used inside LocaleProvider");
  }
  return value;
}
